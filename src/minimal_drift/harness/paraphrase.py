"""Per-session paraphrase of the intent description -- the honest source of epsilon.

AP2 defines `IntentMandate.natural_language_description` as "generated by the
shopping agent, and confirmed by the user". So the exact wording differs between
sessions of the *same* user intent, and sometimes the agent's summary quietly
loses a qualifier the user said out loud.

That is the real baseline error floor: not model sampling noise, but lossy
intent capture. Modelling it keeps the counterfactual honest -- without it
epsilon is 0 by construction and "ATE net of baseline" means nothing. The
budget cap and currency always survive paraphrase, so the mandate is unchanged.
"""

from __future__ import annotations

import hashlib
import re

_PREFIXES = (
    ("Buy ", "I want to buy "),
    ("Buy ", "Order "),
    ("Buy ", "Looking for "),
    ("Order ", "Buy "),
    ("I need ", "Buy "),
)
_BUDGET_PHRASES = (
    ("under ", "below "),
    ("under ", "for less than "),
    ("under ", "with a budget of "),
)

# Qualifiers a lossy agent summary plausibly drops. Dropping one is what makes an
# omission attack's premise real rather than assumed.
_QUALIFIERS = (
    "waterproof ",
    "noise-cancelling ",
    "decaf ",
    "ergonomic ",
    "pre-seasoned ",
    "paperback ",
    "dark roast ",
    "GPS ",
    "adjustable lumbar support ",
    "with a laptop sleeve ",
    "whole ",
    "trail ",
)


def _bits(seed: int, salt: str) -> int:
    return int.from_bytes(hashlib.sha256(f"{salt}|{seed}".encode()).digest()[:4], "big")


def paraphrase(nl: str, seed: int) -> str:
    """Deterministic session paraphrase of `nl`. Budget cap and currency preserved.

    seed % 5 == 0 returns the canonical wording unchanged.
    """
    if seed % 5 == 0:
        return nl
    out = nl
    for src, dst in (_PREFIXES[_bits(seed, "prefix") % len(_PREFIXES)],):
        if out.startswith(src):
            out = dst + out[len(src) :]
    for src, dst in (_BUDGET_PHRASES[_bits(seed, "budget") % len(_BUDGET_PHRASES)],):
        out = out.replace(src, dst, 1)
    # 1 session in 6 loses one spoken qualifier.
    if _bits(seed, "drop") % 6 == 0:
        present = [q for q in _QUALIFIERS if q.lower() in out.lower()]
        if present:
            q = present[_bits(seed, "which") % len(present)]
            out = re.sub(re.escape(q), "", out, count=1, flags=re.IGNORECASE)
    return re.sub(r"\s{2,}", " ", out).strip()
